/** Resolves [key] against Settings > language, recomposing automatically
 * when it changes, and fills its placeholders from [args]. Falls back to
 * French if a key is somehow missing a translation for the current
 * language (should never happen — every entry above carries all three). */
@Composable
fun t(key: Tr, vararg args: Any): String {
    val appViewModel = LocalAppViewModel.current
    val prefs by appViewModel.prefs.collectAsState()
    return resolve(key, prefs.settings.language, args)
}

/** [one] or [other] depending on [count] and the language's plural rule
 * (French: 0 and 1 are singular; English: only 1; Japanese has no plural,
 * [one] and [other] simply carry the same text). [count] is passed as the
 * first placeholder, followed by [args]. */
@Composable
fun tCount(one: Tr, other: Tr, count: Int, vararg args: Any): String {
    val appViewModel = LocalAppViewModel.current
    val prefs by appViewModel.prefs.collectAsState()
    return resolve(pluralKey(one, other, count, prefs.settings.language), prefs.settings.language, arrayOf(count, *args))
}

/** [tCount] outside composition. */
fun textCount(one: Tr, other: Tr, count: Int, vararg args: Any): String =
    resolve(pluralKey(one, other, count, AppLocale.current), AppLocale.current, arrayOf(count, *args))

private fun pluralKey(one: Tr, other: Tr, count: Int, language: AppLanguage): Tr = when (language) {
    AppLanguage.FR -> if (count <= 1) one else other
    else -> if (count == 1) one else other
}

/** Same as [t], for code outside composition — reads [AppLocale.current]
 * synchronously, so it doesn't update by itself on a language change. */
fun Tr.text(vararg args: Any): String = resolve(this, AppLocale.current, args)

private fun resolve(key: Tr, language: AppLanguage, args: Array<out Any>): String {
    val entry = TRANSLATIONS.getValue(key)
    val raw = entry[language] ?: entry.getValue(AppLanguage.FR)
    // Only format when there's something to fill: plain texts may hold a
    // literal "%" that String.format would choke on.
    return if (args.isEmpty()) raw else String.format(Locale.ROOT, raw, *args)
}
